// Complete Sri Kanya Family Restaurants Menu Data
export interface MenuItem {
  id: string;
  name: string;
  nameHi?: string; // Hindi name
  nameTe?: string; // Telugu name
  description: string;
  descriptionHi?: string; // Hindi description
  descriptionTe?: string; // Telugu description
  price: number;
  category: string;
  isVeg: boolean;
  isSignature?: boolean;
  isSpecial?: boolean;
  image: string;
  maxQuantity?: number; // Maximum quantity allowed per order
  minQuantity?: number; // Minimum quantity required
  bulkPricing?: { quantity: number; price: number }[]; // Bulk pricing tiers
  preparationTime?: number; // Preparation time in minutes
  popularity?: number; // Popularity score (1-10)
  trending?: boolean; // Is this item trending
  isDisabled?: boolean; // Whether item is disabled/hidden from customers
}

// Helper function to get localized text
export function getLocalizedText(item: any, field: 'name' | 'description', language: 'en' | 'hi' | 'te'): string {
  if (language === 'en') {
    return item[field];
  }
  
  const localizedField = `${field}${language === 'hi' ? 'Hi' : 'Te'}`;
  return item[localizedField] || item[field]; // Fallback to English
}

