// Function to test if a Cloudinary image is accessible
export async function testImageAccessibility(imageUrl: string): Promise<boolean> {
  try {
    const response = await fetch(imageUrl, { method: 'HEAD' });
    return response.ok;
  } catch (error) {
    console.error(`Image accessibility test failed for ${imageUrl}:`, error);
    return false;
  }
}

